# Вводим строку с клавиатуры
text = input("Введите строку: ")

# Создаём пустую строку для символов без повторов
result = ""

# Перебираем каждый символ исходной строки
for char in text:
    # Добавляем символ, если его ещё нет в результате
    if char not in result:
        result += char

# Выводим строку без повторяющихся символов
print("Строка без повторов:", result)